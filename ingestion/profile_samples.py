        "",
        "## Duplicate and grain checks",
        "",
        f"- Exact duplicate inspection rows: "
        f"{exact_duplicate_count(inspection_records):,}",
        f"- Estimated inspection events: "
        f"{grain_results['estimated_inspection_events']:,}",
        f"- Inspection events with multiple violation rows: "
        f"{grain_results['events_with_multiple_rows']:,}",
        f"- Largest number of rows for one inspection event: "
        f"{grain_results['largest_rows_per_event']:,}",
        f"- CAMIS values with multiple DBA names in the sample: "
        f"{name_results['camis_with_multiple_names']:,}",
        f"- Exact duplicate 311 rows: "
        f"{exact_duplicate_count(complaint_records):,}",
        f"- Duplicate 311 `unique_key` values: "
        f"{duplicate_complaint_ids:,}",
        "",
        "## Restaurant-name harmonization",
        "",
        "This profile applies the same syntax normalization and reviewed "
