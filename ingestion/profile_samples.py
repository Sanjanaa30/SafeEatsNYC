# Running the Program
# main(): The starting point of the script when you run it:
# Loads the inspection records and 311 complaint records from their files.
# Runs build_report() to generate the markdown content.
# Creates the docs folder if it doesn't exist yet.
# Saves everything into data_profile.md and prints a success message in your terminal.

def main() -> None:
    """Load samples and write a reproducible profile report."""

    inspection_records = load_records(INSPECTION_SAMPLE_PATH)
    complaint_records = load_records(COMPLAINT_SAMPLE_PATH)
    report = build_report(inspection_records, complaint_records)

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(report, encoding="utf-8")

    print("Data profile complete.")
    print(f"Report: {REPORT_PATH}")


if __name__ == "__main__":
    main()
