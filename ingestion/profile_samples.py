# Opens a JSON file, reads it, and makes sure it's actually a list of objects (dictionaries). If the file format is broken, it raises an error.
def load_records(path: Path) -> list[dict[str, Any]]:
    """Load and validate a JSON-list sample."""

    with path.open(mode="r", encoding="utf-8") as input_file:
        records = json.load(input_file)

    if not isinstance(records, list):
        raise TypeError(
            f"{path.name} must contain a JSON list."
        )

    if not all(isinstance(record, dict) for record in records):
        raise TypeError(f"Every record in {path.name} must be an object.")

    return records

# Converts a list of dictionaries into a pandas DataFrame, replacing any blank strings with missing values (pd.NA).
def create_dataframe(records: list[dict[str, Any]]) -> pd.DataFrame:
    """Convert records to a DataFrame and treat blanks as missing."""

    return pd.DataFrame(records).replace(r"^\s*$", pd.NA, regex=True)

# Checking Data Quality
# The below functions analyze different parts of the data to see how clean or messy it is:
# exact_duplicate_count(): Checks if there are any exact, identical rows repeated in the file and counts them.
def exact_duplicate_count(records: list[dict[str, Any]]) -> int:
    """Count completely identical JSON records."""

    canonical_records = {
        json.dumps(record, sort_keys=True, separators=(",", ":"))
        for record in records
    }

    return len(records) - len(canonical_records)

# missing_value_profile(): Counts how many items are missing for each important field and calculates the missing percentage.
def missing_value_profile(dataframe: pd.DataFrame, fields: list[str]) -> pd.DataFrame:
    """Calculate missing counts for the planned fields."""

    total_rows = len(dataframe)
    rows: list[dict[str, Any]] = []

    for field in fields:
        missing_count = (
            int(dataframe[field].isna().sum())
            if field in dataframe.columns
            else total_rows
        )

        rows.append(
            {
                "field": field,
                "missing_count": missing_count,
                "missing_percent": (
                    round(missing_count / total_rows * 100, 2)
                    if total_rows
                    else 0.0
                ),
            }
        )

    return pd.DataFrame(rows)

# value_counts_table(): Counts how often each unique value appears (like how many restaurants got an "A" grade versus a "B" grade).
def value_counts_table(dataframe: pd.DataFrame, field: str) -> pd.DataFrame:
    """Return value frequencies, including missing values."""

    if field not in dataframe.columns:
        return pd.DataFrame(
            [{field: "<field absent>", "row_count": len(dataframe)}]
        )

    values = (
        dataframe[field]
        .fillna("<missing>")
        .astype(str)
        .value_counts(dropna=False)
        .rename_axis(field)
        .reset_index(name="row_count")
    )

    return values

# date_profile(): Checks if dates can be read properly, finds the earliest and latest dates, and looks for broken dates or special placeholder dates (like the year 1900).
def date_profile(dataframe: pd.DataFrame, field: str) -> dict[str, Any]:
    """Profile whether a field can be parsed as a date."""

    parsed_dates = pd.to_datetime(dataframe[field], errors="coerce")
    valid_dates = parsed_dates.dropna()
    source_present = int(dataframe[field].notna().sum())
    invalid_count = int(source_present - parsed_dates.notna().sum())
    sentinel_1900_count = int((parsed_dates.dt.year == 1900).sum())

    return {
        "minimum": valid_dates.min().isoformat() if not valid_dates.empty else "<none>",
        "maximum": valid_dates.max().isoformat() if not valid_dates.empty else "<none>",
        "invalid_count": invalid_count,
        "sentinel_1900_count": sentinel_1900_count,
    }

# coordinate_profile(): Checks latitude and longitude to see how many coordinates are missing, set to zero, or located completely outside of New York City.
def coordinate_profile(
    dataframe: pd.DataFrame,
) -> dict[str, int]:
    """Measure missing, zero, and out-of-NYC coordinates."""

    latitude = pd.to_numeric(dataframe["latitude"], errors="coerce")
    longitude = pd.to_numeric(dataframe["longitude"], errors="coerce")
    missing_coordinates = latitude.isna() | longitude.isna()
    zero_coordinates = (latitude == 0) | (longitude == 0)

    outside_nyc = (
        ~missing_coordinates
        & ~zero_coordinates
        & (
            ~latitude.between(40.4, 41.0)
            | ~longitude.between(-74.3, -73.6)
        )
    )

    return {
        "missing": int(missing_coordinates.sum()),
        "zero": int(zero_coordinates.sum()),
        "outside_nyc_bounds": int(outside_nyc.sum()),
        "usable": int(
            (~missing_coordinates & ~zero_coordinates & ~outside_nyc).sum()
        ),
    }

# numeric_profile(): Checks number fields (like inspection scores) to make sure they are actually numbers and counts any non-numeric text.
def numeric_profile(dataframe: pd.DataFrame, field: str) -> dict[str, Any]:
    """Check whether source values can become numeric."""

    numeric_values = pd.to_numeric(dataframe[field], errors="coerce")
    source_present = int(dataframe[field].notna().sum())
    non_numeric_count = int(source_present - numeric_values.notna().sum())
    valid_values = numeric_values.dropna()

    return {
        "minimum": float(valid_values.min()) if not valid_values.empty else None,
        "maximum": float(valid_values.max()) if not valid_values.empty else None,
        "non_numeric_count": non_numeric_count,
    }


# inspection_grain_profile(): Checks for repeated rows that belong to the same inspection, helping to identify potential data duplication issues.
def inspection_grain_profile(dataframe: pd.DataFrame) -> dict[str, int]:
    """Measure repeated rows belonging to the same inspection."""

    grouping_fields = ["camis", "inspection_date", "inspection_type"]
    group_sizes = dataframe.groupby(grouping_fields, dropna=False).size()

    return {
        "estimated_inspection_events": len(group_sizes),
        "events_with_multiple_rows": int((group_sizes > 1).sum()),
        "largest_rows_per_event": (
            int(group_sizes.max()) if not group_sizes.empty else 0
        ),
    }

# restaurant_name_profile(): Checks if the same restaurant ID (camis) ever has multiple different names (dba) in the sample.
def restaurant_name_profile(dataframe: pd.DataFrame) -> dict[str, int]:
    """Find CAMIS values associated with multiple DBA names."""

    names_per_restaurant = dataframe.groupby("camis")["dba"].nunique(
        dropna=True
    )

    return {
        "unique_camis": int(dataframe["camis"].nunique(dropna=True)),
        "camis_with_multiple_names": int((names_per_restaurant > 1).sum()),
    }

# name_harmonization_profile(): This function cleans up and standardizes restaurant names. 
# It removes weird punctuation, applies known nicknames or aliases (e.g., matching a brand name properly), checks for co-branded restaurants (like a store with two brands inside), and flags names that contain separators like & or AND so you can review them manually.
def name_harmonization_profile(dataframe: pd.DataFrame) -> dict[str, Any]:
    """Profile shared normalization, aliases, and reviewed co-brands."""

    aliases, co_brands, fast_food_brands = load_name_references(
        REFERENCE_DIRECTORY
    )

    restaurants = dataframe[["camis", "dba"]].drop_duplicates().copy()
    restaurants["name_syntax_normalized"] = restaurants["dba"].map(normalize_name)
    restaurants["name_normalized"] = restaurants["dba"].map(
        lambda name: canonicalize_name(name, aliases)
    )
    restaurants["brand_candidates"] = restaurants["dba"].map(
        lambda name: brand_candidates(name, aliases, co_brands)
    )
    restaurants["confirmed_fast_food_brands"] = restaurants["brand_candidates"].map(
        lambda candidates: tuple(
            brand for brand in candidates if brand in fast_food_brands
        )
    )

    alias_rows = restaurants[
        restaurants["name_syntax_normalized"] != restaurants["name_normalized"]
    ]
    co_brand_rows = restaurants[
        restaurants["name_syntax_normalized"].isin(co_brands)
    ]

    collision_groups = (
        restaurants.groupby("name_normalized", dropna=False)["dba"]
        .agg(lambda values: tuple(sorted(set(values))))
    )
    collision_groups = collision_groups[collision_groups.map(len) > 1]
    collision_table = pd.DataFrame(
        [
            {
                "name_normalized": name,
                "source_dba_values": " | ".join(source_names),
            }
            for name, source_names in collision_groups.items()
        ]
    )

    co_brand_table = pd.DataFrame(
        [
            {
                "location_name_normalized": location_name,
                "brands_preserved": " + ".join(brand_names),
                "sample_camis": int(
                    co_brand_rows.loc[
                        co_brand_rows["name_syntax_normalized"] == location_name,
                        "camis",
                    ].nunique()
                ),
            }
            for location_name, brand_names in co_brands.items()
        ]
    )

    separator_mask = restaurants["dba"].str.contains(
        r"[/&,]|\bAND\b",
        case=False,
        regex=True,
        na=False,
    )
    separator_table = (
        restaurants.loc[
            separator_mask,
            ["dba", "name_syntax_normalized", "camis"],
        ]
        .groupby(["dba", "name_syntax_normalized"], as_index=False)["camis"]
        .nunique()
        .rename(columns={"camis": "sample_camis"})
        .sort_values("dba")
    )
    separator_table["policy"] = separator_table["name_syntax_normalized"].map(
        lambda name: (
            "REVIEWED CO-BRAND"
            if name in co_brands
            else "REVIEW ONLY - NOT SPLIT"
        )
    )

    return {
        "unique_source_names": int(restaurants["dba"].nunique()),
        "unique_syntax_names": int(restaurants["name_syntax_normalized"].nunique()),
        "unique_canonical_names": int(restaurants["name_normalized"].nunique()),
        "alias_camis": int(alias_rows["camis"].nunique()),
        "co_brand_camis": int(co_brand_rows["camis"].nunique()),
        "confirmed_fast_food_camis": int(
            restaurants.loc[
                restaurants["confirmed_fast_food_brands"].map(bool),
                "camis",
            ].nunique()
        ),
        "separator_names": int(restaurants.loc[separator_mask, "dba"].nunique()),
        "collision_table": collision_table,
        "co_brand_table": co_brand_table,
        "separator_table": separator_table,
    }

# format_table(): Converts a Pandas table into a clean Markdown code block so it looks neat in the final document.
def format_table(dataframe: pd.DataFrame) -> str:
    """Format a DataFrame without adding another dependency."""

    return "```\n" + dataframe.to_string(index=False) + "\n```"

